/** 判断这个错误是否属于“模型/网络不可用”，可以用离线回答兜底 */
export function shouldUseMockReply(message: string): boolean {
  return !NON_MOCK_ERRORS.some((keyword) => message.includes(keyword))
}

export interface MockPickOptions {
  /** 本轮是否带图 */
  hasImages: boolean
  /** 会话 id，用于通用池轮换 */
  threadId: string
}

const genericCursor = new Map<string, number>()
const imageCursor = new Map<string, number>()

function nextFrom(pool: string[], cursor: Map<string, number>, key: string): string {
  const index = cursor.get(key) ?? 0
  cursor.set(key, index + 1)
  return pool[index % pool.length]
}

/** 按关键词匹配；未命中时按会话轮换通用回答 */
export function pickMockReply(question: string, options: MockPickOptions): string {
  if (options.hasImages) {
    return nextFrom(IMAGE_REPLIES, imageCursor, options.threadId)
  }

  const text = question.toLowerCase()
  let best: MockReply | null = null
  let bestScore = 0
  for (const item of MOCK_REPLIES) {
    let score = 0
    for (const keyword of item.keywords) {
      if (text.includes(keyword.toLowerCase())) score += 1
    }
    if (score > bestScore) {
      best = item
      bestScore = score
    }
  }
  if (best) return best.reply

  return nextFrom(GENERIC_REPLIES, genericCursor, options.threadId)
}

/** 把回答切成分片，模拟流式输出（避免使用 lookbehind，兼容旧版 iOS JSCore） */
export function splitMockReply(text: string): string[] {
  const chunks: string[] = []
  let buffer = ''
  for (const char of text) {
    buffer += char
    if ('。！？；\n'.includes(char) && buffer.length >= 10) {
      chunks.push(buffer)
      buffer = ''
    } else if (buffer.length >= 42) {
      chunks.push(buffer)
      buffer = ''
    }
  }
  if (buffer) chunks.push(buffer)
  return chunks
}

/** 逐段写入目标消息，模拟正常的流式回复 */
export async function playMockReply(
  target: { content: string; streaming?: boolean; error?: boolean; mock?: boolean },
  reply: string,
  intervalMs = 45,
): Promise<void> {
  target.content = ''
  target.error = false
  target.mock = true
  target.streaming = true
  for (const chunk of splitMockReply(reply)) {
    target.content += chunk
    await new Promise((resolve) => setTimeout(resolve, intervalMs))
  }
  target.streaming = false
}
